import pandas as pd
import io
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files
from scipy import sparse
from scipy.sparse.linalg import spsolve
from scipy.signal import savgol_filter

# ==============================
# USER PARAMETERS
# ==============================
LAMBDA = 1e5
P = 0.01
NITER = 10

WINDOW = 7   # SG (must be odd)
POLY = 3

OFFSET = 4000

PEAK_REGION = (548, 555)
BACKGROUND_REGION = (560, 610)

SAVE_OUTPUT = True

# ==============================
# ALS FUNCTION
# ==============================
def als_baseline(y, lam, p, niter):
    L = len(y)
    D = sparse.diags([1, -2, 1], [0, -1, -2], shape=(L, L-2))
    w = np.ones(L)

    baselines = []

    for i in range(niter):
        W = sparse.diags(w, 0)
        Z = W + lam * D.dot(D.T)
        z = spsolve(Z, w * y)

        baselines.append(z.copy())
        w = p * (y > z) + (1 - p) * (y < z)

    return z, baselines

# ==============================
# FILE UPLOAD
# ==============================
print("Upload CSV with 'OOI LIBS' and 'Data File'")
uploaded = files.upload()

if uploaded:

    file_name = next(iter(uploaded))
    df = pd.read_csv(io.BytesIO(uploaded[file_name]))

    # Corrected column names based on available data
    wavelength = df['wavelength (nm)'].values
    raw = df['intensity'].values

    print(f"Loaded {len(wavelength)} data points")

    # ==============================
    # STEP 1: SG SMOOTHING
    # ==============================
    smoothed = savgol_filter(raw, WINDOW, POLY)

    # ==============================
    # STEP 2: ALS BASELINE
    # ==============================
    baseline, baseline_iters = als_baseline(smoothed, LAMBDA, P, NITER)
    corrected = smoothed - baseline

    # ==============================
    # CREATE FIGURE
    # ==============================
    fig, axs = plt.subplots(1, 2, figsize=(14, 5)) # Changed to 1 row, 2 columns

    # --------------------------------
    # (a) BASELINE SEPARATION (OFFSET)
    # --------------------------------
    ax = axs[0] # Updated indexing for 1D axs

    ax.plot(wavelength, raw + OFFSET, alpha=0.5, label="Raw Spectra", linewidth=1.5)
    ax.plot(wavelength, smoothed, label="SG Smoothed", linewidth=1.5)
    ax.plot(wavelength, baseline, '--', linewidth=2, label="ALS Baseline", color='black')
    ax.plot(wavelength, corrected - OFFSET, label="Corrected Spectra", linewidth=1.5)



    ax.set_title("(a) SG + ALS Baseline Separation")
    ax.set_xlabel("Wavelength (nm)")
    ax.set_ylabel("Intensity")
    ax.legend()
    ax.grid(True)

    # --------------------------------
    # (b) ALS CONVERGENCE + LEGEND
    # --------------------------------
    ax = axs[1] # Updated indexing for 1D axs

    baseline_matrix = np.array(baseline_iters)

    im = ax.imshow(baseline_matrix,
                   aspect='auto',
                   extent=[wavelength.min(), wavelength.max(), 1, NITER],
                   origin='lower',
                   cmap='plasma')

    ax.set_title("(b) ALS Iterative Baseline Convergence")
    ax.set_xlabel("Wavelength (nm)")
    ax.set_ylabel("Iteration")

    # Select iterations
    selected_iters = [0, int(NITER/3), int(2*NITER/3), NITER-1]
    colors = ['white', 'yellow', 'cyan', 'red']

    for i, c in zip(selected_iters, colors):
        norm_curve = baseline_iters[i] / np.max(baseline_iters[i]) * NITER

        ax.plot(wavelength,
                norm_curve,
                linestyle='--',
                linewidth=1.5,
                color=c,
                label=f"Iter {i+1}")

    ax.legend(title="Iterations", fontsize=9)

    fig.colorbar(im, ax=ax, label="Baseline Intensity")


    # ==============================
    # FINAL DISPLAY
    # ==============================
    plt.tight_layout()
    plt.show()

    # Save figure as JPG
    fig.savefig("SG_ALS_LIBS_processed.jpg", dpi=600)

    # ==============================
    # SAVE OUTPUT
    # ==============================
    if SAVE_OUTPUT:
        output_df = pd.DataFrame({
            "Wavelength": wavelength,
            "Raw": raw,
            "Smoothed_SG": smoothed,
            "Baseline_ALS": baseline,
            "Corrected": corrected
        })

        output_df.to_csv("SG_ALS_LIBS_processed.csv", index=False)
        print("Saved: SG_ALS_LIBS_processed.csv")

else:
    print("No file uploaded.")