import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from scipy.interpolate import interp1d
from google.colab import files
import io

# ==========================
# 1. Upload Files
# ==========================
print("Upload PROCESSED spectrum CSV (wavelength, intensity)")
uploaded1 = files.upload()

print("Upload PURE element spectrum CSV (Wavelength (nm), Intensity)")
uploaded2 = files.upload()

# Load files
proc_file = list(uploaded1.keys())[0]
pure_file = list(uploaded2.keys())[0]

processed = pd.read_csv(io.StringIO(uploaded1[proc_file].decode('utf-8')))
pure = pd.read_csv(io.StringIO(uploaded2[pure_file].decode('utf-8')))

# Ensure correct column names
processed.columns = ["wavelength", "intensity"]
pure.columns = ["wavelength", "intensity"]

# ==========================
# 2. Input Target Lines
# ==========================
line_input = input("Enter element wavelengths (nm), comma separated: ")
target_lines = [float(x.strip()) for x in line_input.split(",")]

# Window size (nm)
window_input = input("Enter window size around each line (e.g., 0.5 nm): ")
window = float(window_input.replace(',', '.').replace(' nm', '').strip())

# ==========================
# 3. Validation Function
# ==========================
def validation_coefficient(p, s):
    p = np.array(p)
    s = np.array(s)

    if len(p) != len(s) or len(p) == 0:
        return np.nan

    p_mean = np.mean(p)
    s_mean = np.mean(s)

    numerator = np.sum((p - p_mean) * (s - s_mean))
    denominator = np.sqrt(np.sum((p - p_mean)**2) * (np.sum((s - s_mean)**2)))

    if denominator == 0:
        return np.nan

    return numerator / denominator

# ==========================
# 4. Process Each Line
# ==========================
results = []

for line in target_lines:
    # Extract window
    p_region = processed[
        (processed["wavelength"] >= line - window) &
        (processed["wavelength"] <= line + window)
    ]

    s_region = pure[
        (pure["wavelength"] >= line - window) &
        (pure["wavelength"] <= line + window)
    ]

    if len(p_region) < 5 or len(s_region) < 5:
        print(f"Skipping {line} nm (insufficient data)")
        continue

    # Interpolate pure spectrum to processed grid
    interp_func = interp1d(
        s_region["wavelength"],
        s_region["intensity"],
        kind='linear',
        fill_value="extrapolate"
    )

    s_interp = interp_func(p_region["wavelength"])

    # Normalize
    p_norm = p_region["intensity"] / np.max(p_region["intensity"])
    s_norm = s_interp / np.max(s_interp)

    # Validation coefficient
    vc = validation_coefficient(p_norm, s_norm)
    results.append((line, vc))

    # ==========================
    # 5. Plot (Separate Window)
    # ==========================
    fig, ax = plt.subplots(figsize=(6,4)) # Create figure and axes

    ax.plot(p_region["wavelength"], p_norm, label="Processed", linewidth=2)
    ax.plot(p_region["wavelength"], s_norm, '--', label="Pure", linewidth=2)

    ax.set_title(f"Line: {line} nm | VC = {vc:.3f}")
    ax.set_xlabel("Wavelength (nm)")
    ax.set_ylabel("Normalized Intensity")
    ax.legend()
    ax.grid()

    # Save the figure instead of showing it interactively in the loop
    plot_filename = f"line_plot_{line:.2f}nm.png"
    plt.savefig(plot_filename, dpi=300)
    plt.close(fig) # Close the specific figure to free up memory

# ==========================
# 6. Summary Table
# ==========================
results_df = pd.DataFrame(results, columns=["Wavelength (nm)", "Validation Coefficient"])

print("\n=== Validation Results ===")
print(results_df)

# Save results
results_df.to_csv("validation_results.csv", index=False)
print("\nSaved: validation_results.csv")
print(f"\nIndividual plots for each line have been saved as 'line_plot_XXX.XXnm.png' files in your Colab environment.")