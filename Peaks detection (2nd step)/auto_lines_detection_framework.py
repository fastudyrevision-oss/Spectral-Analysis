import numpy as np
import pandas as pd
from scipy.signal import find_peaks
import matplotlib.pyplot as plt
from google.colab import files
import io

# -------------------------------
# FILE UPLOAD
# -------------------------------
print("Upload CSV file:")
uploaded = files.upload()

file_name = list(uploaded.keys())[0]
# Fix: Reverted from delim_whitespace=True to sep='\t'
data = pd.read_csv(io.StringIO(uploaded[file_name].decode('latin-1')), sep=',', skiprows=6)

# -------------------------------
# DATA HANDLING
# -------------------------------
data.columns = data.columns.str.strip()

if 'Wavelength' in data.columns and 'Intensity' in data.columns:
    wavelength = data['Wavelength'].values
    intensity = data['Intensity'].values
else:
    wavelength = data.iloc[:, 0].values
    intensity = data.iloc[:, 1].values

# -------------------------------
# BASELINE FILTER FUNCTION
# -------------------------------
def remove_baseline_peaks(inten, peaks, window=20, k=2):
    filtered = []

    for p in peaks:
        left = max(0, p - window)
        right = min(len(inten), p + window)

        region = inten[left:right]

        baseline = np.percentile(region, 50)
        noise = np.std(region)

        if inten[p] > baseline + k * noise:
            filtered.append(p)

    return np.array(filtered)

# -------------------------------
# GLOBAL THRESHOLD
# -------------------------------
noise_level = np.std(intensity[:int(len(intensity)*0.1)])
height_threshold =  1.2* noise_level

# -------------------------------

# Initialize lists to store all detected peak data
all_peak_wavelengths = []
all_peak_intensities = []

# -------------------------------
# MAIN PLOTTING (SINGLE GRAPH)
# -------------------------------
fig, ax = plt.subplots(figsize=(15, 8)) # Single subplot

# Detect peaks for the entire spectrum
peaks, props = find_peaks(intensity, height=height_threshold, prominence=0.01)

# Remove baseline peaks
peaks = remove_baseline_peaks(intensity, peaks)

peak_wl = wavelength[peaks]
peak_int = intensity[peaks]

# Store detected peaks for CSV output
all_peak_wavelengths.extend(peak_wl)
all_peak_intensities.extend(peak_int)

# Plot the entire spectrum
ax.plot(wavelength, intensity, color='red', linewidth=1.5)
ax.scatter(peak_wl, peak_int, color='black', s=50)


ax.set_xlabel("Wavelength (nm)", fontsize=20)
ax.set_ylabel("\nIntensity", fontsize=20)
ax.tick_params(axis='both', which='major', labelsize=16)
ax.grid(False)

plt.tight_layout()
plt.savefig('Automatic peaks identification.jpg', dpi=600)
plt.show()

# -------------------------------
# Save detected peaks to CSV
# -------------------------------
detected_peaks_df = pd.DataFrame({
    'Wavelength (nm)': all_peak_wavelengths,
    'Intensity': all_peak_intensities
})
detected_peaks_df.to_csv('detected_peaks.csv', index=False)

"""# NIST matching"""

import pandas as pd
import numpy as np
from google.colab import files
import io
import matplotlib.pyplot as plt # Ensure matplotlib is imported for plotting

# -------------------------------
# FILE UPLOAD
# -------------------------------
print("Upload DETECTED PEAKS file:")
uploaded_peaks = files.upload()

if not uploaded_peaks:
    raise ValueError("No detected peaks file uploaded!")

peaks_file = list(uploaded_peaks.keys())[0]

print("Upload NIST DATABASE file:")
uploaded_nist = files.upload()

if not uploaded_nist:
    raise ValueError("No NIST file uploaded!")

nist_file = list(uploaded_nist.keys())[0]

# -------------------------------
# LOAD DETECTED PEAKS
# -------------------------------
peaks = pd.read_csv(io.StringIO(uploaded_peaks[peaks_file].decode('utf-8')))

# Standardize column name
peaks.columns = [c.strip() for c in peaks.columns]

if "Wavelength (nm)" not in peaks.columns:
    raise ValueError("Detected peaks file must contain 'Wavelength (nm)' column")

# -------------------------------
# LOAD NIST DATABASE
# -------------------------------
nist = pd.read_csv(io.StringIO(uploaded_nist[nist_file].decode('utf-8')))

# Clean column names
nist.columns = [c.strip() for c in nist.columns]

# Expected columns (flexible handling)
possible_wl_cols = ["Wavelength", "wavelength", "Wavelength (nm)"]
possible_Aki_cols = ["Aki", "Intensity"] # Removed "Rel_Int" from here to avoid conflict with relative_intensity
possible_element_cols = ["element", "Element"]
possible_rel_int_cols = ["relative_intensity", "Relative_Intensity", "Rel_Int"] # New for relative intensity

# Detect wavelength column
wl_col = next((c for c in possible_wl_cols if c in nist.columns), None)
if wl_col is None:
    raise ValueError("NIST file must contain a wavelength column")

# Detect intensity (Aki) column
aki_col = next((c for c in possible_Aki_cols if c in nist.columns), None)

# Detect relative intensity column
rel_int_col = next((c for c in possible_rel_int_cols if c in nist.columns), None)

# Detect element column
element_col = next((c for c in possible_element_cols if c in nist.columns), None)
if element_col is None:
    print("Warning: NIST file does not contain an 'element' column. Element information will not be included in results.")

# Rename for consistency
nist = nist.rename(columns={wl_col: "Wavelength"})

if aki_col:
    nist = nist.rename(columns={aki_col: "Aki"})
else:
    nist["Aki"] = 1  # fallback if no intensity

if rel_int_col:
    nist = nist.rename(columns={rel_int_col: "relative_intensity"})
else:
    nist["relative_intensity"] = 1 # fallback if no relative intensity, so it doesn't affect score multiplication

if element_col:
    nist = nist.rename(columns={element_col: "Element"})
else:
    nist["Element"] = "Unknown" # fallback if no element column

# Convert to numeric
nist["Wavelength"] = pd.to_numeric(nist["Wavelength"], errors='coerce')
nist["Aki"] = pd.to_numeric(nist["Aki"], errors='coerce').fillna(0)
nist["relative_intensity"] = pd.to_numeric(nist["relative_intensity"], errors='coerce').fillna(1) # Fill with 1 so it doesn't diminish score

nist = nist.dropna(subset=["Wavelength"])

# -------------------------------
# MATCHING PARAMETERS
# -------------------------------
tolerance = 0.2 # nm (adjustable)

results = []

# -------------------------------
# MATCHING PROCESS
# -------------------------------
for _, peak in peaks.iterrows():
    wl_obs = peak["Wavelength (nm)"]

    candidates = nist[np.abs(nist["Wavelength"] - wl_obs) <= tolerance]

    if candidates.empty:
        results.append({
            "Observed_WL": wl_obs,
            "Matched_WL": None,
            "Delta": None,
            "Aki": 0,
            "relative_intensity": 0, # Add relative_intensity to output
            "Score": 0,
            "Element": None
        })
        continue

    for _, row in candidates.iterrows():
        wl_nist = row["Wavelength"]
        delta = abs(wl_nist - wl_obs)

        # Scoring: (Aki * relative_intensity) weighted + proximity
        # Base score from Aki and proximity
        score = row["Aki"] / (delta + 1e-6)

        # Apply relative intensity weight if available and greater than 0
        if "relative_intensity" in row.index and row["relative_intensity"] > 0:
            score *= row["relative_intensity"]

        results.append({
            "Observed_WL": wl_obs,
            "Matched_WL": wl_nist,
            "Delta": delta,
            "Aki": row["Aki"],
            "relative_intensity": row["relative_intensity"], # Add relative_intensity to output
            "Score": score,
            "Element": row["Element"]
        })

# -------------------------------
# CREATE DATAFRAME
# -------------------------------
results_df = pd.DataFrame(results)

# -------------------------------
# BEST MATCH PER PEAK
# -------------------------------
if not results_df.empty:
    # Ensure 'Score' column is numeric before idxmax
    results_df['Score'] = pd.to_numeric(results_df['Score'], errors='coerce')
    best_matches = results_df.loc[
        results_df.groupby("Observed_WL")["Score"].idxmax()
    ]
else:
    best_matches = pd.DataFrame()

# -------------------------------
# SAVE OUTPUT
# -------------------------------
output_file = "LIBS_matching_results.csv"
best_matches.to_csv(output_file, index=False)

print(f"\n✅ Results saved as: {output_file}")
files.download(output_file)

# -------------------------------
# DISPLAY RESULTS
# -------------------------------
print("\n=== ALL MATCHES ===")
print(results_df.head())

print("\n=== BEST MATCHES ===")
print(best_matches)

