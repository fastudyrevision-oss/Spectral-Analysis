import pandas as pd
from google.colab import files
import io

# -------------------------------
# UPLOAD MULTIPLE CSV FILES
# -------------------------------
print("Upload ALL element result CSV files (Ca, Fe, Mg, etc.):")
uploaded = files.upload()

if not uploaded:
    raise ValueError("No files uploaded!")

all_data = []

# -------------------------------
# LOAD & VALIDATE FILES
# -------------------------------
for filename in uploaded.keys():
    df = pd.read_csv(io.StringIO(uploaded[filename].decode('utf-8')))

    # Clean column names
    df.columns = [c.strip() for c in df.columns]

    # Required columns check
    required_cols = ["Observed_WL", "Score", "Element"]
    for col in required_cols:
        if col not in df.columns:
            raise ValueError(f"{filename} must contain column: {col}")

    # Keep only valid matches
    df = df[df["Score"] > 0]

    all_data.append(df)

# Combine all files
combined = pd.concat(all_data, ignore_index=True)

# -------------------------------
# STEP 1: PIVOT (ELEMENT vs WAVELENGTH)
# -------------------------------
pivot = combined.pivot_table(
    index="Matched_WL",
    columns="Element",
    values="Score",
    aggfunc="max"
).fillna(0)

# -------------------------------
# STEP 2: FIND WINNER PER ROW
# -------------------------------
# Calculate Max_Score and Winner using only numeric columns
pivot["Max_Score"] = pivot.max(axis=1, numeric_only=True)
pivot["Winner"] = pivot.idxmax(axis=1, numeric_only=True)

# Reset index for saving
result = pivot.reset_index()

# -------------------------------
# STEP 3: SUMMARY STATISTICS
# -------------------------------
summary = result["Winner"].value_counts().reset_index()
summary.columns = ["Element", "Wins"]

# Add total score contribution
score_sum = combined.groupby("Element")["Score"].sum().reset_index()
score_sum.columns = ["Element", "Total_Score"]

# Merge summary
final_summary = pd.merge(summary, score_sum, on="Element")

# Sort by wins
final_summary = final_summary.sort_values(by="Wins", ascending=False)

# -------------------------------
# FINAL DECISION
# -------------------------------
final_element = final_summary.iloc[0]["Element"]

# -------------------------------
# SAVE OUTPUT
# -------------------------------
result.to_csv("peak_wise_element_competition.csv", index=False)
final_summary.to_csv("final_element_ranking.csv", index=False)

# -------------------------------
# PRINT RESULTS
# -------------------------------
print("\n=== PEAK-WISE COMPETITION ===")
print(result.head())

print("\n=== FINAL ELEMENT SUMMARY ===")
print(final_summary)

print(f"\n🏆 FINAL IDENTIFIED ELEMENT: {final_element}")

# Download files
files.download("peak_wise_element_competition.csv")
