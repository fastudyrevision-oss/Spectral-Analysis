# 7. EXTRACT NUMBERS FROM CONFIRMED WAVELENGTH CELLS
# ============================================================

def extract_numbers(value):

    """
    Example:

    '257.51, 308.22, 309.27, 394.40'

    becomes

    [257.51, 308.22, 309.27, 394.40]
    """

    if pd.isna(value):

        return []


    text = str(value)


    numbers = re.findall(

        r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?",

        text

    )


    return [

        float(number)

        for number in numbers

    ]


