# 14. FUNCTION TO GET LOCAL SPECTRUM
# ============================================================

def get_local_profile(

    spectrum,

    wavelength,

    half_width=2.0

):

    mask = (

        spectrum["Wavelength"]

        >=

        wavelength - half_width

    ) & (

        spectrum["Wavelength"]

        <=

        wavelength + half_width

    )


    local = spectrum.loc[
        mask
    ].copy()


    return local


