# 3. GENERAL CSV READER
# ============================================================

def read_csv_flexible(file_bytes):

    """
    Reads CSV files with either normal comma separation
    or automatically detected separators.
    """

    attempts = [
        {"sep": None, "engine": "python"},
        {"sep": ","},
        {"sep": "\t"}
    ]


    for options in attempts:

        try:

            df = pd.read_csv(

                io.BytesIO(file_bytes),

                **options

            )

            if len(df.columns) >= 2:

                return df

        except Exception:

            continue


    raise ValueError(
        "Could not read the uploaded CSV file."
    )


# ============================================================
# 4. FIND WAVELENGTH COLUMN
# ============================================================

def find_wavelength_column(df):

    columns = list(df.columns)


    # --------------------------------------------------------
    # Exact/common names
    # --------------------------------------------------------

    preferred = [

        "Wavelength",

        "Wavelength (nm)",

        "wavelength",

        "wavelength (nm)",

        "WL",

        "wl",

        "Lambda",

        "lambda"

    ]


    for name in preferred:

        if name in columns:

            return name


    # --------------------------------------------------------
    # Flexible search
    # --------------------------------------------------------

    for col in columns:

        name = (

            str(col)
            .lower()
            .replace(" ", "")
            .replace("_", "")

        )


        if (

            "wavelength" in name
            or
            name == "wl"
            or
            name == "lambda"

        ):

            return col


    return None


# ============================================================
# 5. FIND INTENSITY COLUMN
# ============================================================

def find_intensity_column(df):

    preferred = [

        "Intensity",

        "intensity",

        "Intensity (a.u.)",

        "Intensity (AU)",

        "Signal",

        "signal"

    ]


    for name in preferred:

        if name in df.columns:

            return name


    for col in df.columns:

        name = (

            str(col)
            .lower()
            .replace(" ", "")
            .replace("_", "")

        )


        if (

            "intensity" in name
            or
            name == "signal"

        ):

            return col


    return None


# ============================================================
# 6. STANDARDIZE SPECTRUM
# ============================================================

def standardize_spectrum(df):

    df = df.copy()


    df.columns = (

        df.columns
        .astype(str)
        .str.strip()

    )


    wavelength_col = (
        find_wavelength_column(df)
    )


    intensity_col = (
        find_intensity_column(df)
    )


    if wavelength_col is None:

        raise ValueError(

            "Wavelength column was not found."

        )


    if intensity_col is None:

        raise ValueError(

            "Intensity column was not found."

        )


    result = pd.DataFrame({

        "Wavelength":

            pd.to_numeric(

                df[wavelength_col],

                errors="coerce"

            ),

        "Intensity":

            pd.to_numeric(

                df[intensity_col],

                errors="coerce"

            )

    })


    result = result.dropna(

        subset=[
            "Wavelength",
            "Intensity"
        ]

    )


    result = (

        result

        .sort_values(
            "Wavelength"
        )

        .reset_index(
            drop=True
        )

    )


    return result


