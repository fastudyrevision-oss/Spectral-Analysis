# ============================================================

def nearest_spectrum_peak(
    wavelength,
    tolerance=0.15
):

    if len(
        continuous_peak_wavelengths
    ) == 0:

        return None


    differences = np.abs(

        continuous_peak_wavelengths
        -
        wavelength

    )


    nearest = int(

        np.argmin(
            differences
        )

    )


    if (

        differences[nearest]
        <=
        tolerance

    ):

        return {

            "index":

                int(
                    continuous_peak_indices[
                        nearest
                    ]
                ),

            "wavelength":

                float(
                    continuous_peak_wavelengths[
                        nearest
                    ]
                ),

            "prominence":

                float(
                    continuous_prominences[
                        nearest
                    ]
                )

        }


    return None


