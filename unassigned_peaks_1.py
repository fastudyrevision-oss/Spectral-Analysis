# 6. STANDARDIZE PROCESSED SPECTRUM
# ============================================================

def standardize_spectrum(df):

    df = df.copy()


    df.columns = (

        df.columns

        .astype(str)

        .str.strip()

    )


    wl_col = find_wavelength_column(df)

    int_col = find_intensity_column(df)


    # --------------------------------------------------------
    # If proper column names are not available,
    # try first two columns.
    # --------------------------------------------------------

    if wl_col is None or int_col is None:

        temp = pd.DataFrame({

            "Wavelength":

                pd.to_numeric(

                    df.iloc[:, 0],

                    errors="coerce"

                ),

            "Intensity":

                pd.to_numeric(

                    df.iloc[:, 1],

                    errors="coerce"

                )

        })


    else:

        temp = pd.DataFrame({

            "Wavelength":

                pd.to_numeric(

                    df[wl_col],

                    errors="coerce"

                ),

            "Intensity":

                pd.to_numeric(

                    df[int_col],

                    errors="coerce"

                )

        })


    temp = temp.dropna(

        subset=[

            "Wavelength",

            "Intensity"

        ]

    )


    temp = (

        temp

        .sort_values(

            "Wavelength"

        )

        .reset_index(

            drop=True

        )

    )


    return temp


