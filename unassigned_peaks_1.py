    # LOCAL SPECTRAL WINDOW
    # ========================================================

    local_mask = (

        spectrum_wavelength
        >=
        target_wavelength
        -
        LOCAL_WINDOW

    ) & (

        spectrum_wavelength
        <=
        target_wavelength
        +
        LOCAL_WINDOW

    )


    local_wavelength = (

        spectrum_wavelength[
            local_mask
        ]

    )


    local_intensity = (

        spectrum_intensity[
            local_mask
        ]

    )


    # ========================================================
    # REMOVE TARGET PEAK FROM BACKGROUND ESTIMATION
    # ========================================================

    background_mask = (

        np.abs(

            local_wavelength
            -
            target_wavelength

        )

        >

        PEAK_GUARD

    )


    background_values = (

        local_intensity[
            background_mask
        ]

    )


    # --------------------------------------------------------
    # Fallback
    # --------------------------------------------------------

    if len(
        background_values
    ) < MIN_LOCAL_POINTS:

        background_values = (
            local_intensity
        )


    # ========================================================
    # LOCAL BACKGROUND
    # ========================================================

    local_background = float(

        np.median(

            background_values

        )

    )


    # ========================================================
    # ROBUST LOCAL NOISE
    # ========================================================

    median_absolute_deviation = float(

        np.median(

            np.abs(

                background_values
                -
                local_background

            )

        )

    )


    local_noise = (

        1.4826
        *
        median_absolute_deviation

    )


    # --------------------------------------------------------
    # Fallback to standard deviation
    # --------------------------------------------------------

    if (

        local_noise <= 0
        or
        not np.isfinite(
            local_noise
        )

    ):

        local_noise = float(

            np.std(

                background_values,

                ddof=1

            )

        )


    # --------------------------------------------------------
    # Final numerical safeguard
    # --------------------------------------------------------

    if (

        local_noise <= 0
        or
        not np.isfinite(
            local_noise
        )

    ):

        local_noise = 1e-12


    # ========================================================
    # SIGNAL
    # ========================================================

    signal = (

        observed_intensity
        -
        local_background

    )


    # Negative signal is not considered useful
    # for recovery.

    positive_signal = max(

        signal,

        0.0

    )


    # ========================================================
    # SNR
    # ========================================================

    snr = (

        positive_signal
        /
        (
            local_noise
            +
            1e-12
        )

    )


    # ========================================================
    # CONTINUOUS-SPECTRUM PROMINENCE
    # ========================================================

    matched_peak = (

        nearest_spectrum_peak(

            target_wavelength,

            tolerance=0.15

        )

    )


