def normalize_positive(series):

    values = (

        pd.to_numeric(

            series,

            errors="coerce"

        )

        .fillna(0)

        .clip(
            lower=0
        )

    )


    maximum = values.max()


    if (

        maximum <= 0
        or
        not np.isfinite(
            maximum
        )

    ):

        return pd.Series(

            np.zeros(
                len(values)
            ),

            index=values.index

        )


    return (

        values
        /
        maximum

    )


