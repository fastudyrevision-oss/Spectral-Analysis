df = pd.read_csv("peak_wise_element_competition.csv")

# Ensure required columns exist
df.columns = [c.strip() for c in df.columns]

# Standard naming
df = df.rename(columns={
    "Matched_WL": "wavelength", # Corrected from "Observed_WL" to "Matched_WL"
    "Winner": "element",
    "Max_Score": "score"
})

# ==============================
# CREATE MULTI-PANEL FIGURE
# ==============================
fig, axes = plt.subplots(3, 3, figsize=(18, 15))
axes = axes.flatten()

# ==============================
# (A) Competition Map
# ==============================
sc = axes[0].scatter(
    df["wavelength"], df["element"],
    c=df["score"], s=60
)
axes[0].set_title("(A) Element Competition Map")
axes[0].set_xlabel("Wavelength (nm)")
axes[0].set_ylabel("Element")
axes[0].grid()
fig.colorbar(sc, ax=axes[0], label="Score")

# ==============================
# (B) Score vs Delta
# ==============================
# The 'delta' column is not directly available in 'peak_wise_element_competition.csv' unless it's a pivot result.
# If it is meant to be part of the individual matches, that data is not in this DF.
# For now, commenting out to avoid error, or will need to re-evaluate source data if 'delta' is crucial here.
# For this plot, if we are visualizing the 'peak_wise_element_competition', 'delta' is not part of that structure.
# It's likely found in the 'LIBS_matching_results.csv' or 'best_matches' which has individual match details.
# Let's check if there is a 'Delta' in df to use, if not, we skip or show a placeholder.
if 'Delta' in df.columns:
    axes[1].scatter(df["Delta"], df["score"], alpha=0.7)
    axes[1].axhline(0.5, linestyle='--')
    axes[1].axvline(0.1, linestyle='--')
    axes[1].set_title("(B) Score vs Δλ")
    axes[1].set_xlabel("Δλ (nm)")
    axes[1].set_ylabel("Score")
    axes[1].grid()
else:
    axes[1].text(0.3, 0.5, "'Delta' column not found for Score vs Δλ", fontsize=12)
    axes[1].set_title("(B) Score vs Δλ (Data Missing)")

# ==============================
# (C) Heatmap
# ==============================
df["wl_bin"] = pd.cut(df["wavelength"], bins=20)

pivot = df.pivot_table(
    values="score",
    index="element",
    columns="wl_bin",
    aggfunc="mean",
    observed=False # Added to suppress FutureWarning
)

sns.heatmap(pivot, ax=axes[2], cmap="viridis")
axes[2].set_title("(C) Element Dominance Heatmap")

# ==============================
# (D) Multi-line Profile
# ==============================
for el in df["element"].unique():
    sub = df[df["element"] == el]
    axes[3].plot(sub["wavelength"], sub["score"], marker='o', label=el)

axes[3].set_title("(D) Multi-line Confidence")
axes[3].set_xlabel("Wavelength")
axes[3].set_ylabel("Score")
axes[3].legend(fontsize=6)
axes[3].grid()

# ==============================
# (E) Confidence Ranking
# ==============================
confidence = df.groupby("element")["score"].mean().sort_values()

axes[4].barh(confidence.index, confidence.values)
axes[4].set_title("(E) Element Confidence")
axes[4].set_xlabel("Average Score")
axes[4].grid()

