import pandas as pd
from google.colab import files
import io

# ==========================================
# UPLOAD ELEMENT MATCH FILES
# ==========================================
print("Upload all NIST matched element CSV files:")
uploaded = files.upload()

if not uploaded:
    raise ValueError("No files uploaded!")

all_data = []

# ==========================================
# LOAD FILES
# ==========================================
required_cols = ["Observed_WL",
                 "Matched_WL",
                 "Score",
                 "Element"]

for filename in uploaded.keys():

    df = pd.read_csv(
        io.StringIO(uploaded[filename].decode('utf-8'))
    )

    df.columns = df.columns.str.strip()

    missing = [c for c in required_cols if c not in df.columns]

    if missing:
        raise ValueError(
            f"{filename} missing columns: {missing}"
        )

    # keep only positive scores
    df = df[df["Score"] > 0]

    all_data.append(df)

# ==========================================
# COMBINE ALL ELEMENT FILES
# ==========================================
combined = pd.concat(all_data,
                     ignore_index=True)


# ==========================================
# PEAK-WISE COMPETITION
# ==========================================
pivot = combined.pivot_table(
            index="Matched_WL",
            columns="Element",
            values="Score",
            aggfunc="max"
        ).fillna(0)


pivot["Max_Score"] = pivot.max(axis=1)
pivot["Winner"] = pivot.idxmax(axis=1)

competition = pivot.reset_index()


# ==========================================
# ELEMENT RANKING
# ==========================================
wins = competition["Winner"].value_counts()

summary = wins.reset_index()
summary.columns = ["Element","Wins"]

score_sum = (
    combined.groupby("Element")["Score"]
    .sum()
    .reset_index()
)

score_sum.columns = [
    "Element",
    "Total_Score"
]

summary = pd.merge(
            summary,
            score_sum,
            on="Element"
         )

summary = summary.sort_values(
            "Wins",
            ascending=False
          )

final_element = summary.iloc[0]["Element"]


# ==========================================
# DIRECT OUTPUT OF SECOND CODE
# ==========================================
winner_lines = competition[
    ["Matched_WL","Winner"]
].copy()

winner_lines.rename(
    columns={
        "Winner":"Winning_Element",
        "Matched_WL":"Observed_Wavelength"
    },
    inplace=True
)

winner_lines["NIST_Matched_Wavelength"] = \
    winner_lines["Observed_Wavelength"]

winner_lines = winner_lines[
    [
        "Winning_Element",
        "Observed_Wavelength",
        "NIST_Matched_Wavelength"
    ]
]

winner_lines = winner_lines.round(2)

winner_lines = winner_lines.sort_values(
                    ["Winning_Element",
                     "Observed_Wavelength"]
               )


# ==========================================
# SAVE FILES
# ==========================================
competition.to_csv(
    "peak_wise_element_competition.csv",
    index=False
)

summary.to_csv(
    "final_element_ranking.csv",
    index=False
)

winner_lines.to_csv(
    "competition_winner_elements_with_nist_matches.csv",
    index=False
)


# ==========================================
# DISPLAY RESULTS
# ==========================================
print("\n===== FINAL ELEMENT SUMMARY =====")
print(summary)

print(f"\n🏆 Final Identified Element : {final_element}")


print("\n===== Winner Lines =====")
for element, grp in winner_lines.groupby("Winning_Element"):

    values = list(
        zip(
            grp["Observed_Wavelength"],
            grp["NIST_Matched_Wavelength"]
        )
    )

    print(f"\n{element} ({len(values)} lines)")
    print(values)


